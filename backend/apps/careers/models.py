from django.db import models
from apps.accounts.models import UserProfile


class CareerRecommendationSession(models.Model):
    """Historical snapshot of a career recommendation generation run."""

    profile = models.ForeignKey(
        UserProfile,
        on_delete=models.CASCADE,
        related_name='career_sessions'
    )
    interests = models.TextField(blank=True)
    work_preference = models.CharField(max_length=100, blank=True)
    target_industries = models.CharField(max_length=200, blank=True)
    target_analysis = models.TextField(blank=True)
    readiness_level = models.CharField(max_length=100, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        verbose_name = 'Career Recommendation Session'
        verbose_name_plural = 'Career Recommendation Sessions'
        ordering = ['-created_at']

    def __str__(self):
        return f"Session for {self.profile.user.email} on {self.created_at.strftime('%Y-%m-%d %H:%M')}"


class CareerRecommendation(models.Model):
    """A recommended career path generated by Gemini."""

    session = models.ForeignKey(
        CareerRecommendationSession,
        on_delete=models.CASCADE,
        related_name='recommendations'
    )
    profile = models.ForeignKey(
        UserProfile,
        on_delete=models.CASCADE,
        related_name='career_recommendations'
    )
    title = models.CharField(max_length=200)
    match_score = models.IntegerField(help_text="Match score 0-100")
    suitability_reason = models.TextField()
    market_outlook_bd = models.TextField()
    required_skills = models.JSONField(default=list)
    matched_skills = models.JSONField(default=list)
    missing_skills = models.JSONField(default=list)
    growth_potential = models.CharField(max_length=100, blank=True)
    recommended_next_steps = models.JSONField(default=list)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        verbose_name = 'Career Recommendation'
        verbose_name_plural = 'Career Recommendations'
        ordering = ['-match_score', '-created_at']

    def __str__(self):
        return f"{self.title} ({self.match_score}%) for {self.profile.user.email}"


class SkillGapReport(models.Model):
    """Detailed skill comparison and gap analysis for a specific recommendation."""

    recommendation = models.OneToOneField(
        CareerRecommendation,
        on_delete=models.CASCADE,
        related_name='skill_gap_report'
    )
    profile = models.ForeignKey(
        UserProfile,
        on_delete=models.CASCADE,
        related_name='skill_gap_reports'
    )
    target_role = models.CharField(max_length=200)
    match_percentage = models.IntegerField()
    strengths = models.JSONField(default=list)
    critical_missing_skills = models.JSONField(default=list)
    learning_priority = models.JSONField(default=list)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        verbose_name = 'Skill Gap Report'
        verbose_name_plural = 'Skill Gap Reports'
        ordering = ['-created_at']

    def __str__(self):
        return f"Gap Report: {self.target_role} ({self.match_percentage}%)"
